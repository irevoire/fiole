//! Property checks to make sure a codec really behaves as it claims.
//!
//! They only rely on [`arbitrary`], so they can be run with any property
//! testing library built on it, like [`arbtest`](https://docs.rs/arbtest),
//! or from a fuzzer like [`cargo fuzz`](https://github.com/rust-fuzz/cargo-fuzz).

use std::{borrow::Borrow, fmt::Debug};

use arbitrary::{Arbitrary, Unstructured};

use crate::codec::{Decode, DecodingVec, Encode, EncodingVec, SelfDelimiting};

/// Checks that `C` really is [`SelfDelimiting`] on a random value of type `O`.
///
/// It generates a random prefix, a random value and a random suffix, then:
/// 1. Encodes the value with `C` right after the prefix, and checks the prefix
///    hasn't been modified.
/// 2. Appends the suffix and decodes the value from right after the prefix.
/// 3. Checks the decoded value equals the original one and that exactly the
///    suffix is left to read.
///
/// If `C` fails to encode the value, the value is skipped: some codecs refuse
/// some inputs.
///
/// `O` is the owned type that gets generated, it must [`Borrow`] the item
/// encoded by `C`. For example, use [`String`] for a codec encoding [`str`].
/// When `O` doesn't implement [`Arbitrary`], use [`check_self_delimiting_with`].
///
/// # Panics
///
/// Panics with a description of the failure when the property doesn't hold.
///
/// # Errors
///
/// Only returns an error when `u` doesn't contain enough data to generate the inputs.
///
/// ```
/// use byteorder::BE;
/// use fiole::codec::{SizedCodec, Str, U32, check_self_delimiting};
///
/// arbtest::arbtest(|u| check_self_delimiting::<U32<BE>, u32>(u));
/// arbtest::arbtest(|u| check_self_delimiting::<SizedCodec<Str>, String>(u));
/// ```
pub fn check_self_delimiting<'a, C, O>(u: &mut Unstructured<'a>) -> arbitrary::Result<()>
where
    C: Encode + Decode + SelfDelimiting,
    O: Arbitrary<'a> + Borrow<<C as Encode>::Item>,
    <C as Encode>::Item: Debug,
    <C as Decode>::Item: PartialEq<<C as Encode>::Item> + Debug,
    <C as Decode>::Error: Debug,
{
    check_self_delimiting_with::<C, O>(u, O::arbitrary)
}

/// Same as [`check_self_delimiting`], but the value is generated by `generate`.
///
/// Useful when the value doesn't implement [`Arbitrary`], or to restrict the generated values.
pub fn check_self_delimiting_with<'a, C, O>(
    u: &mut Unstructured<'a>,
    generate: impl FnOnce(&mut Unstructured<'a>) -> arbitrary::Result<O>,
) -> arbitrary::Result<()>
where
    C: Encode + Decode + SelfDelimiting,
    O: Borrow<<C as Encode>::Item>,
    <C as Encode>::Item: Debug,
    <C as Decode>::Item: PartialEq<<C as Encode>::Item> + Debug,
    <C as Decode>::Error: Debug,
{
    let prefix: Vec<u8> = u.arbitrary()?;
    let item = generate(u)?;
    let item: &<C as Encode>::Item = item.borrow();
    let suffix: Vec<u8> = u.arbitrary()?;

    let mut vec = EncodingVec::new().edit();
    vec.extend(&prefix);
    let Ok(vec) = C::encode(vec.make_fresh(), item) else {
        return Ok(());
    };
    let mut bytes = vec.finish();
    assert!(
        bytes.starts_with(&prefix),
        "Encoding {item:?} modified the bytes written before it.\nprefix: {prefix:?}\nbytes: {bytes:?}",
    );
    let encoded = bytes[prefix.len()..].to_vec();
    bytes.extend(&suffix);

    let mut decoder = DecodingVec::new(bytes);
    decoder.take_next(prefix.len());
    let decoded = C::decode(&mut decoder).unwrap_or_else(|error| {
        panic!(
            "Couldn't decode {item:?} when followed by other bytes: {error:?}\nencoded: {encoded:?}\nsuffix: {suffix:?}"
        )
    });
    assert!(
        decoded == *item,
        "Decoded {decoded:?} instead of {item:?}\nencoded: {encoded:?}\nsuffix: {suffix:?}",
    );
    let remaining = decoder.consume();
    assert!(
        remaining == suffix,
        "Decoding {item:?} didn't stop at the end of its own bytes.\nencoded: {encoded:?}\nsuffix: {suffix:?}\nleft to read: {remaining:?}",
    );
    Ok(())
}

#[cfg(test)]
// The closures can't be removed: the lifetime of `Unstructured` must stay generic for arbtest
#[allow(clippy::redundant_closure)]
mod test {
    use std::convert::Infallible;

    use crate::codec::{
        Decode, DecodingVec, Encode, EncodingVec, Fresh, SelfDelimiting, U8, check_self_delimiting,
    };

    /// Encodes like [`U8`] but decodes everything till the end.
    enum Greedy {}

    impl Encode for Greedy {
        type Item = u8;
        type Error = Infallible;

        fn encode(
            into: EncodingVec<Fresh>,
            item: &Self::Item,
        ) -> Result<EncodingVec<Fresh>, Self::Error> {
            U8::encode(into, item)
        }
    }

    impl Decode for Greedy {
        type Item = u8;
        type Error = std::io::Error;

        fn decode(bytes: &mut DecodingVec) -> Result<Self::Item, Self::Error> {
            let ret = U8::decode(bytes);
            bytes.consume();
            ret
        }
    }

    impl SelfDelimiting for Greedy {}

    /// Decodes like [`U8`] but erases the bytes written before it.
    enum Eraser {}

    impl Encode for Eraser {
        type Item = u8;
        type Error = Infallible;

        fn encode(
            into: EncodingVec<Fresh>,
            item: &Self::Item,
        ) -> Result<EncodingVec<Fresh>, Self::Error> {
            let mut ret = into.edit();
            ret.vec.clear();
            ret.push(*item);
            Ok(ret.make_fresh())
        }
    }

    impl Decode for Eraser {
        type Item = u8;
        type Error = std::io::Error;

        fn decode(bytes: &mut DecodingVec) -> Result<Self::Item, Self::Error> {
            U8::decode(bytes)
        }
    }

    impl SelfDelimiting for Eraser {}

    #[test]
    fn valid_codec() {
        arbtest::arbtest(|u| check_self_delimiting::<U8, u8>(u));
    }

    #[test]
    #[should_panic(expected = "didn't stop at the end of its own bytes")]
    fn catches_codecs_reading_too_much() {
        arbtest::arbtest(|u| check_self_delimiting::<Greedy, u8>(u));
    }

    #[test]
    #[should_panic(expected = "modified the bytes written before it")]
    fn catches_codecs_erasing_previous_bytes() {
        arbtest::arbtest(|u| check_self_delimiting::<Eraser, u8>(u));
    }
}
