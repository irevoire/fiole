//! Property checks to make sure a codec really behaves as it claims.
//!
//! They only rely on [`arbitrary`], so they can be run with any property
//! testing library built on it, like [`arbtest`](https://docs.rs/arbtest),
//! or from a fuzzer like [`cargo fuzz`](https://github.com/rust-fuzz/cargo-fuzz).

use std::{borrow::Borrow, cmp::Ordering, fmt::Debug};

use arbitrary::{Arbitrary, Unstructured};

use crate::codec::{Decode, DecodingVec, Encode, EncodingVec, SelfDelimiting};

/// Checks that a random value of type `O` survives a round-trip through `C`.
///
/// It generates a random prefix and a random value, then:
/// 1. Encodes the value with `C` right after the prefix, and checks the prefix
///    hasn't been modified.
/// 2. Decodes the value from right after the prefix.
/// 3. Checks the decoded value equals the original one and that all the bytes
///    have been read.
///
/// Works with every codec, final or [`SelfDelimiting`]. To also check that a
/// codec can be followed by other bytes, use [`check_self_delimiting`].
///
/// If `C` fails to encode the value, the value is skipped: some codecs refuse
/// some inputs.
///
/// `O` is the owned type that gets generated, it must [`Borrow`] the item
/// encoded by `C`. For example, use [`String`] for a codec encoding [`str`].
/// When `O` doesn't implement [`Arbitrary`], use [`check_round_trip_with`].
///
/// # Panics
///
/// Panics with a description of the failure when the property doesn't hold.
///
/// # Errors
///
/// Only returns an error when `u` doesn't contain enough data to generate the inputs.
///
/// ```
/// use fiole::codec::{Bytes, Str, check_round_trip};
///
/// arbtest::arbtest(check_round_trip::<Str, String>);
/// arbtest::arbtest(check_round_trip::<Bytes, Vec<u8>>);
/// ```
pub fn check_round_trip<C, O>(u: &mut Unstructured) -> arbitrary::Result<()>
where
    C: Encode + Decode,
    O: for<'a> Arbitrary<'a> + Borrow<<C as Encode>::Item>,
    <C as Encode>::Item: Debug,
    <C as Decode>::Item: PartialEq<<C as Encode>::Item> + Debug,
    <C as Decode>::Error: Debug,
{
    check_round_trip_with::<C, O>(u, O::arbitrary)
}

/// Same as [`check_round_trip`], but the value is generated by `generate`.
///
/// Useful when the value doesn't implement [`Arbitrary`], or to restrict the generated values.
pub fn check_round_trip_with<'a, C, O>(
    u: &mut Unstructured<'a>,
    generate: impl FnOnce(&mut Unstructured<'a>) -> arbitrary::Result<O>,
) -> arbitrary::Result<()>
where
    C: Encode + Decode,
    O: Borrow<<C as Encode>::Item>,
    <C as Encode>::Item: Debug,
    <C as Decode>::Item: PartialEq<<C as Encode>::Item> + Debug,
    <C as Decode>::Error: Debug,
{
    let prefix: Vec<u8> = u.arbitrary()?;
    let item = generate(u)?;
    check::<C>(&prefix, item.borrow(), &[]);
    Ok(())
}

/// Checks that `C` really is [`SelfDelimiting`] on a random value of type `O`.
///
/// It generates a random prefix, a random value and a random suffix, then:
/// 1. Encodes the value with `C` right after the prefix, and checks the prefix
///    hasn't been modified.
/// 2. Appends the suffix and decodes the value from right after the prefix.
/// 3. Checks the decoded value equals the original one and that exactly the
///    suffix is left to read.
///
/// It's a stricter version of [`check_round_trip`].
///
/// If `C` fails to encode the value, the value is skipped: some codecs refuse
/// some inputs.
///
/// `O` is the owned type that gets generated, it must [`Borrow`] the item
/// encoded by `C`. For example, use [`String`] for a codec encoding [`str`].
/// When `O` doesn't implement [`Arbitrary`], use [`check_self_delimiting_with`].
///
/// # Panics
///
/// Panics with a description of the failure when the property doesn't hold.
///
/// # Errors
///
/// Only returns an error when `u` doesn't contain enough data to generate the inputs.
///
/// ```
/// use byteorder::BE;
/// use fiole::codec::{SizedCodec, Str, U32, check_self_delimiting};
///
/// arbtest::arbtest(check_self_delimiting::<U32<BE>, u32>);
/// arbtest::arbtest(check_self_delimiting::<SizedCodec<Str>, String>);
/// ```
pub fn check_self_delimiting<C, O>(u: &mut Unstructured) -> arbitrary::Result<()>
where
    C: Encode + Decode + SelfDelimiting,
    O: for<'a> Arbitrary<'a> + Borrow<<C as Encode>::Item>,
    <C as Encode>::Item: Debug,
    <C as Decode>::Item: PartialEq<<C as Encode>::Item> + Debug,
    <C as Decode>::Error: Debug,
{
    check_self_delimiting_with::<C, O>(u, O::arbitrary)
}

/// Same as [`check_self_delimiting`], but the value is generated by `generate`.
///
/// Useful when the value doesn't implement [`Arbitrary`], or to restrict the generated values.
pub fn check_self_delimiting_with<'a, C, O>(
    u: &mut Unstructured<'a>,
    generate: impl FnOnce(&mut Unstructured<'a>) -> arbitrary::Result<O>,
) -> arbitrary::Result<()>
where
    C: Encode + Decode + SelfDelimiting,
    O: Borrow<<C as Encode>::Item>,
    <C as Encode>::Item: Debug,
    <C as Decode>::Item: PartialEq<<C as Encode>::Item> + Debug,
    <C as Decode>::Error: Debug,
{
    let prefix: Vec<u8> = u.arbitrary()?;
    let item = generate(u)?;
    let suffix: Vec<u8> = u.arbitrary()?;
    check::<C>(&prefix, item.borrow(), &suffix);
    Ok(())
}

/// Checks that `C` keeps the order of two random values of type `O`.
///
/// It generates two different values, encodes them with `C` and checks that
/// their encoded bytes compare the same way as the values. This is what makes
/// a codec usable for ordered keys, with [`crate::Keyspace::range`] or
/// [`crate::Keyspace::first_key_value`].
///
/// If `C` fails to encode one of the values, they're skipped: some codecs refuse
/// some inputs.
///
/// `O` is the owned type that gets generated, it must [`Borrow`] the item
/// encoded by `C` and its [`Ord`] implementation defines the expected order.
/// When `O` doesn't implement [`Arbitrary`], use [`check_order_preserving_with`].
///
/// # Panics
///
/// Panics with a description of the failure when the property doesn't hold.
///
/// # Errors
///
/// Only returns an error when `u` doesn't contain enough data to generate the inputs.
///
/// ```
/// use fiole::codec::{OrderedU32, Str, check_order_preserving};
///
/// arbtest::arbtest(check_order_preserving::<OrderedU32, u32>);
/// arbtest::arbtest(check_order_preserving::<Str, String>);
/// ```
pub fn check_order_preserving<C, O>(u: &mut Unstructured) -> arbitrary::Result<()>
where
    C: Encode,
    O: for<'a> Arbitrary<'a> + Borrow<<C as Encode>::Item> + Ord + Debug,
{
    check_order_preserving_with::<C, O>(u, O::arbitrary)
}

/// Same as [`check_order_preserving`], but the values are generated by `generate`.
///
/// Useful when the values don't implement [`Arbitrary`], or to restrict the generated values.
pub fn check_order_preserving_with<'a, C, O>(
    u: &mut Unstructured<'a>,
    mut generate: impl FnMut(&mut Unstructured<'a>) -> arbitrary::Result<O>,
) -> arbitrary::Result<()>
where
    C: Encode,
    O: Borrow<<C as Encode>::Item> + Ord + Debug,
{
    let left = generate(u)?;
    let right = generate(u)?;
    let expected = left.cmp(&right);
    if expected == Ordering::Equal {
        return Ok(());
    }
    let (Ok(left_bytes), Ok(right_bytes)) = (
        C::encode_alloc(left.borrow()),
        C::encode_alloc(right.borrow()),
    ) else {
        return Ok(());
    };
    let (left_bytes, right_bytes) = (left_bytes.finish(), right_bytes.finish());
    let got = left_bytes.cmp(&right_bytes);
    assert!(
        got == expected,
        "{left:?} is {expected:?} to {right:?} but its encoding is {got:?}.\nleft: {left_bytes:?}\nright: {right_bytes:?}",
    );
    Ok(())
}

/// Encodes `item` with `C` between `prefix` and `suffix`, decodes it back and
/// checks it's equal to `item` and that only `suffix` is left to read.
fn check<C>(prefix: &[u8], item: &<C as Encode>::Item, suffix: &[u8])
where
    C: Encode + Decode,
    <C as Encode>::Item: Debug,
    <C as Decode>::Item: PartialEq<<C as Encode>::Item> + Debug,
    <C as Decode>::Error: Debug,
{
    let mut vec = EncodingVec::new().edit();
    vec.extend(prefix);
    let Ok(vec) = C::encode(vec.make_fresh(), item) else {
        return;
    };
    let mut bytes = vec.finish();
    assert!(
        bytes.starts_with(prefix),
        "Encoding {item:?} modified the bytes written before it.\nprefix: {prefix:?}\nbytes: {bytes:?}",
    );
    let encoded = bytes[prefix.len()..].to_vec();
    bytes.extend(suffix);

    let mut decoder = DecodingVec::new(bytes);
    decoder.take_next(prefix.len());
    let decoded = C::decode(&mut decoder).unwrap_or_else(|error| {
        panic!("Couldn't decode {item:?}: {error:?}\nencoded: {encoded:?}\nsuffix: {suffix:?}")
    });
    assert!(
        decoded == *item,
        "Decoded {decoded:?} instead of {item:?}\nencoded: {encoded:?}\nsuffix: {suffix:?}",
    );
    let remaining = decoder.consume();
    if suffix.is_empty() {
        assert!(
            remaining.is_empty(),
            "Decoding {item:?} didn't read all of its bytes.\nencoded: {encoded:?}\nleft to read: {remaining:?}",
        );
    } else {
        assert!(
            *remaining == *suffix,
            "Decoding {item:?} didn't stop at the end of its own bytes.\nencoded: {encoded:?}\nsuffix: {suffix:?}\nleft to read: {remaining:?}",
        );
    }
}

#[cfg(test)]
mod test {
    use std::convert::Infallible;

    use crate::codec::{
        Decode, DecodingVec, Encode, EncodingVec, Fresh, SelfDelimiting, U8,
        check_order_preserving, check_round_trip, check_self_delimiting,
    };

    /// Encodes like [`U8`] but decodes everything till the end.
    enum Greedy {}

    impl Encode for Greedy {
        type Item = u8;
        type Error = Infallible;

        fn encode(
            into: EncodingVec<Fresh>,
            item: &Self::Item,
        ) -> Result<EncodingVec<Fresh>, Self::Error> {
            U8::encode(into, item)
        }
    }

    impl Decode for Greedy {
        type Item = u8;
        type Error = std::io::Error;

        fn decode(bytes: &mut DecodingVec) -> Result<Self::Item, Self::Error> {
            let ret = U8::decode(bytes);
            bytes.consume();
            ret
        }
    }

    impl SelfDelimiting for Greedy {}

    /// Decodes like [`U8`] but erases the bytes written before it.
    enum Eraser {}

    impl Encode for Eraser {
        type Item = u8;
        type Error = Infallible;

        fn encode(
            into: EncodingVec<Fresh>,
            item: &Self::Item,
        ) -> Result<EncodingVec<Fresh>, Self::Error> {
            let mut ret = into.edit();
            ret.vec.clear();
            ret.push(*item);
            Ok(ret.make_fresh())
        }
    }

    impl Decode for Eraser {
        type Item = u8;
        type Error = std::io::Error;

        fn decode(bytes: &mut DecodingVec) -> Result<Self::Item, Self::Error> {
            U8::decode(bytes)
        }
    }

    impl SelfDelimiting for Eraser {}

    /// Only keeps the lowest byte of an [`u16`].
    enum Lossy {}

    impl Encode for Lossy {
        type Item = u16;
        type Error = Infallible;

        fn encode(
            into: EncodingVec<Fresh>,
            item: &Self::Item,
        ) -> Result<EncodingVec<Fresh>, Self::Error> {
            U8::encode(into, &(*item as u8))
        }
    }

    impl Decode for Lossy {
        type Item = u16;
        type Error = std::io::Error;

        fn decode(bytes: &mut DecodingVec) -> Result<Self::Item, Self::Error> {
            U8::decode(bytes).map(u16::from)
        }
    }

    /// Writes the byte twice but only reads it once.
    enum Stutter {}

    impl Encode for Stutter {
        type Item = u8;
        type Error = Infallible;

        fn encode(
            into: EncodingVec<Fresh>,
            item: &Self::Item,
        ) -> Result<EncodingVec<Fresh>, Self::Error> {
            let mut ret = into.edit();
            ret.push(*item);
            ret.push(*item);
            Ok(ret.make_fresh())
        }
    }

    impl Decode for Stutter {
        type Item = u8;
        type Error = std::io::Error;

        fn decode(bytes: &mut DecodingVec) -> Result<Self::Item, Self::Error> {
            U8::decode(bytes)
        }
    }

    #[test]
    fn round_trip_of_valid_codecs() {
        arbtest::arbtest(check_round_trip::<U8, u8>);
        // Reading everything till the end is fine for a round-trip
        arbtest::arbtest(check_round_trip::<Greedy, u8>);
    }

    #[test]
    #[should_panic(expected = "instead of")]
    fn round_trip_catches_lossy_codecs() {
        arbtest::arbtest(check_round_trip::<Lossy, u16>);
    }

    #[test]
    #[should_panic(expected = "didn't read all of its bytes")]
    fn round_trip_catches_codecs_reading_too_little() {
        arbtest::arbtest(check_round_trip::<Stutter, u8>);
    }

    #[test]
    #[should_panic(expected = "modified the bytes written before it")]
    fn round_trip_catches_codecs_erasing_previous_bytes() {
        arbtest::arbtest(check_round_trip::<Eraser, u8>);
    }

    #[test]
    fn order_of_valid_codecs() {
        use byteorder::BE;

        use crate::codec::{Str, U32};

        arbtest::arbtest(check_order_preserving::<U8, u8>);
        arbtest::arbtest(check_order_preserving::<U32<BE>, u32>);
        arbtest::arbtest(check_order_preserving::<Str, String>);
    }

    #[test]
    #[should_panic(expected = "but its encoding is")]
    fn order_catches_unordered_codecs() {
        use byteorder::LE;

        use crate::codec::U32;

        arbtest::arbtest(check_order_preserving::<U32<LE>, u32>);
    }

    #[test]
    fn valid_codec() {
        arbtest::arbtest(check_self_delimiting::<U8, u8>);
    }

    #[test]
    #[should_panic(expected = "didn't stop at the end of its own bytes")]
    fn catches_codecs_reading_too_much() {
        arbtest::arbtest(check_self_delimiting::<Greedy, u8>);
    }

    #[test]
    #[should_panic(expected = "modified the bytes written before it")]
    fn catches_codecs_erasing_previous_bytes() {
        arbtest::arbtest(check_self_delimiting::<Eraser, u8>);
    }
}
