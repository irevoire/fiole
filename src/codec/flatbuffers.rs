use std::{convert::Infallible, fmt, marker::PhantomData};

use byteview::ByteView;
use flatbuffers::{Allocator, FlatBufferBuilder, Follow, InvalidFlatbuffer, Verifiable};

use crate::codec::{Decode, DecodingVec, Encode, EncodingVec, Fresh};

/// Small helper trait that says which table is at the root of a [`FlatBuffer`].
/// It's required in order to use the `FlatBuffer` codec defined below.
///
/// ```
/// # #[allow(dead_code, unused_imports, non_upper_case_globals, clippy::all)]
/// # mod dog {
/// #     include!(concat!(env!("CARGO_MANIFEST_DIR"), "/src/codec/flatbuffers/dog_generated.rs"));
/// # }
/// use fiole::codec::FlatBufferRoot;
/// // Generated by `flatc --rust` from `dog.fbs`
/// use dog::Dog;
///
/// impl FlatBufferRoot for Dog<'static> {
///     type Table<'a> = Dog<'a>;
/// }
/// ```
pub trait FlatBufferRoot {
    /// The table generated by `flatc`, borrowing bytes living for `'a`.
    type Table<'a>: Follow<'a, Inner = Self::Table<'a>> + Verifiable + 'a;
}

/// Encode a [FlatBuffer](https://flatbuffers.dev) whose root table is `T`.
///
/// Encoding and decoding never copy the bytes: [`FlatBuffer::decode`] verifies
/// the bytes shared with fjall once, then [`Flat::get`] reads the table straight
/// from them.
///
/// /!\ This codec is final: it decodes everything till the end, so it can only be the last element of a tuple of codecs. To put it anywhere else, wrap it in a [`SizedCodec`](crate::codec::SizedCodec).
///
/// ```
/// # #[allow(dead_code, unused_imports, non_upper_case_globals, clippy::all)]
/// # mod dog {
/// #     include!(concat!(env!("CARGO_MANIFEST_DIR"), "/src/codec/flatbuffers/dog_generated.rs"));
/// # }
/// use fiole::codec::{Flat, FlatBuffer, FlatBufferRoot, Str};
/// use fiole::{Database, KeyspaceCreateOptions};
/// use flatbuffers::FlatBufferBuilder;
/// // Generated by `flatc --rust` from `dog.fbs`
/// use dog::{Color, Dog, DogArgs};
///
/// impl FlatBufferRoot for Dog<'static> {
///     type Table<'a> = Dog<'a>;
/// }
///
/// type DogCodec = FlatBuffer<Dog<'static>>;
///
/// let dir = tempfile::tempdir().unwrap();
/// let db = Database::builder(dir.path()).unwrap();
/// let dogs = db
///     .keyspace::<Str, DogCodec>("dogs", KeyspaceCreateOptions::default)
///     .unwrap();
///
/// let mut builder = FlatBufferBuilder::new();
/// let name = builder.create_string("Kefir");
/// let kefir = Dog::create(&mut builder, &DogArgs {
///     name: Some(name),
///     color: Color::White,
///     paws: 4,
///     drool_liters_per_day: 1.5,
///     meals_per_day: 5,
///     poops_per_day: 4,
///     belly_shaven: true,
/// });
/// builder.finish(kefir, None);
///
/// let mut wtxn = db.write_tx().unwrap();
/// dogs.insert(&mut wtxn, "kefir", &Flat::from_builder(&builder).unwrap()).unwrap();
///
/// let kefir = dogs.get(&wtxn, "kefir").unwrap().unwrap();
/// let kefir = kefir.get();
/// assert_eq!(kefir.name(), Some("Kefir"));
/// assert_eq!(kefir.color(), Color::White);
/// assert!(kefir.belly_shaven());
/// ```
///
/// It can't be followed by anything without a [`SizedCodec`](crate::codec::SizedCodec):
///
/// ```compile_fail,E0599
/// use fiole::codec::{Decode, DecodingVec, FlatBuffer, FlatBufferRoot, U8};
///
/// fn decode<T: FlatBufferRoot>(bytes: &mut DecodingVec) {
///     <(FlatBuffer<T>, U8)>::decode(bytes);
/// }
/// ```
pub struct FlatBuffer<T>(PhantomData<T>);

impl<T: FlatBufferRoot> Encode for FlatBuffer<T> {
    type Item = Flat<T>;
    type Error = Infallible;

    fn encode(
        into: EncodingVec<Fresh>,
        item: &Self::Item,
    ) -> Result<EncodingVec<Fresh>, Self::Error> {
        let mut ret = into.edit();
        ret.extend(item.as_bytes());
        Ok(ret.make_fresh())
    }
}

impl<T: FlatBufferRoot> Decode for FlatBuffer<T> {
    type Item = Flat<T>;
    type Error = InvalidFlatbuffer;

    fn decode(bytes: &mut DecodingVec) -> Result<Self::Item, Self::Error> {
        Flat::new(bytes.consume())
    }
}

/// The bytes of a [FlatBuffer](https://flatbuffers.dev) whose root table is `T`,
/// verified when it's built.
///
/// [`Flat::get`] reads the table without checking anything again.
pub struct Flat<T> {
    bytes: ByteView,
    marker: PhantomData<T>,
}

impl<T: FlatBufferRoot> Flat<T> {
    /// Verifies that `bytes` are a FlatBuffer whose root table is `T`.
    pub fn new(bytes: impl Into<ByteView>) -> Result<Self, InvalidFlatbuffer> {
        let bytes = bytes.into();
        flatbuffers::root::<T::Table<'_>>(&bytes)?;
        Ok(Self {
            bytes,
            marker: PhantomData,
        })
    }

    /// Copies the FlatBuffer written by `builder`, and verifies it.
    ///
    /// # Panics
    ///
    /// Panics if [`FlatBufferBuilder::finish`] wasn't called.
    pub fn from_builder<A: Allocator>(
        builder: &FlatBufferBuilder<'_, A>,
    ) -> Result<Self, InvalidFlatbuffer> {
        Self::new(builder.finished_data())
    }

    /// The root table, read straight from the bytes.
    pub fn get(&self) -> T::Table<'_> {
        // Safety: the bytes were verified in `Flat::new`, and can't be modified
        unsafe { flatbuffers::root_unchecked::<T::Table<'_>>(&self.bytes) }
    }

    /// The bytes of the FlatBuffer.
    pub fn as_bytes(&self) -> &[u8] {
        &self.bytes
    }
}

impl<T> Clone for Flat<T> {
    fn clone(&self) -> Self {
        Self {
            bytes: self.bytes.clone(),
            marker: PhantomData,
        }
    }
}

/// Two FlatBuffers are equal when their bytes are.
impl<T> PartialEq for Flat<T> {
    fn eq(&self, other: &Self) -> bool {
        self.bytes == other.bytes
    }
}

impl<T> Eq for Flat<T> {}

impl<T> fmt::Debug for Flat<T>
where
    T: FlatBufferRoot,
    for<'a> T::Table<'a>: fmt::Debug,
{
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_tuple("Flat").field(&self.get()).finish()
    }
}

#[cfg(test)]
#[allow(dead_code, unused_imports, non_upper_case_globals, clippy::all)]
#[path = "flatbuffers/dog_generated.rs"]
#[rustfmt::skip]
mod dog_generated;

#[cfg(test)]
mod test {
    use flatbuffers::FlatBufferBuilder;

    use super::dog_generated::{Color, Dog, DogArgs};
    use crate::codec::{
        Decode, DecodingVec, Encode, Flat, FlatBuffer, FlatBufferRoot, SizedCodec,
        check_round_trip_with, check_self_delimiting_with,
    };

    impl FlatBufferRoot for Dog<'static> {
        type Table<'a> = Dog<'a>;
    }

    type DogCodec = FlatBuffer<Dog<'static>>;

    /// The fields of a `Dog`, to generate random dogs.
    #[derive(Debug, arbitrary::Arbitrary)]
    struct DogFields {
        name: Option<String>,
        // Any byte, even the colors `dog.fbs` doesn't know
        color: u8,
        paws: u8,
        drool_liters_per_day: f32,
        meals_per_day: u8,
        poops_per_day: u8,
        belly_shaven: bool,
    }

    impl DogFields {
        fn kefir() -> Self {
            Self {
                name: Some("Kefir".to_string()),
                color: Color::White.0,
                paws: 4,
                drool_liters_per_day: 1.5,
                meals_per_day: 5,
                poops_per_day: 4,
                belly_shaven: true,
            }
        }

        fn build(&self) -> Flat<Dog<'static>> {
            let mut builder = FlatBufferBuilder::new();
            let name = self.name.as_deref().map(|name| builder.create_string(name));
            let dog = Dog::create(
                &mut builder,
                &DogArgs {
                    name,
                    color: Color(self.color),
                    paws: self.paws,
                    drool_liters_per_day: self.drool_liters_per_day,
                    meals_per_day: self.meals_per_day,
                    poops_per_day: self.poops_per_day,
                    belly_shaven: self.belly_shaven,
                },
            );
            builder.finish(dog, None);
            Flat::from_builder(&builder).unwrap()
        }

        fn assert_is(&self, dog: Dog<'_>) {
            assert_eq!(dog.name(), self.name.as_deref());
            assert_eq!(dog.color(), Color(self.color));
            assert_eq!(dog.paws(), self.paws);
            // Compare the bits, for `NaN`
            assert_eq!(
                dog.drool_liters_per_day().to_bits(),
                self.drool_liters_per_day.to_bits()
            );
            assert_eq!(dog.meals_per_day(), self.meals_per_day);
            assert_eq!(dog.poops_per_day(), self.poops_per_day);
            assert_eq!(dog.belly_shaven(), self.belly_shaven);
        }
    }

    fn arbitrary_dog(u: &mut arbitrary::Unstructured) -> arbitrary::Result<Flat<Dog<'static>>> {
        Ok(u.arbitrary::<DogFields>()?.build())
    }

    #[test]
    fn round_trip() {
        arbtest::arbtest(|u| check_round_trip_with::<DogCodec, _>(u, arbitrary_dog));
    }

    #[test]
    fn self_delimiting_when_sized() {
        arbtest::arbtest(|u| {
            check_self_delimiting_with::<SizedCodec<DogCodec>, _>(u, arbitrary_dog)
        });
    }

    #[test]
    fn reads_the_fields_back() {
        arbtest::arbtest(|u| {
            let fields: DogFields = u.arbitrary()?;
            let bytes = DogCodec::encode_alloc(&fields.build())
                .unwrap()
                .into_fjall_slice();
            let decoded = DogCodec::decode(&mut bytes.into()).unwrap();
            fields.assert_is(decoded.get());
            fields.assert_is(decoded.clone().get());
            Ok(())
        });
    }

    #[test]
    fn default_values() {
        let mut builder = FlatBufferBuilder::new();
        let dog = Dog::create(&mut builder, &DogArgs::default());
        builder.finish(dog, None);

        let flat = Flat::<Dog<'static>>::from_builder(&builder).unwrap();
        let dog = flat.get();
        assert_eq!(dog.name(), None);
        assert_eq!(dog.paws(), 4);
        assert!(!dog.belly_shaven());
    }

    #[test]
    fn debug() {
        let flat = DogFields::kefir().build();
        assert_eq!(
            format!("{flat:?}"),
            r#"Flat(Dog { name: Some("Kefir"), color: White, paws: 4, drool_liters_per_day: 1.5, meals_per_day: 5, poops_per_day: 4, belly_shaven: true })"#
        );
    }

    #[test]
    fn invalid_bytes_are_refused() {
        let flat = DogFields::kefir().build();
        let bytes = flat.as_bytes();

        assert!(DogCodec::decode(&mut DecodingVec::new([])).is_err());
        assert!(DogCodec::decode(&mut DecodingVec::new(&bytes[..bytes.len() / 2])).is_err());
        assert!(DogCodec::decode(&mut DecodingVec::new([0xff; 16])).is_err());
    }

    #[test]
    fn corrupted_bytes_never_panic() {
        arbtest::arbtest(|u| {
            let mut corrupted = arbitrary_dog(u)?.as_bytes().to_vec();
            for _ in 0..u.int_in_range(1..=4)? {
                let index = u.choose_index(corrupted.len())?;
                corrupted[index] = u.arbitrary()?;
            }
            let len = u.int_in_range(0..=corrupted.len())?;
            // Either the bytes are still valid and can be read, or they're refused
            if let Ok(dog) = DogCodec::decode(&mut DecodingVec::new(&corrupted[..len])) {
                let dog = dog.get();
                let _ = format!("{dog:?}");
            }
            Ok(())
        });
    }

    #[test]
    fn random_bytes_never_panic() {
        arbtest::arbtest(|u| {
            let bytes: Vec<u8> = u.arbitrary()?;
            if let Ok(dog) = DogCodec::decode(&mut DecodingVec::new(bytes)) {
                let _ = format!("{:?}", dog.get());
            }
            Ok(())
        });
    }

    #[test]
    fn decodes_without_copying() {
        let kefir = DogFields::kefir();
        crate::test_alloc::assert_decodes_without_allocating::<DogCodec>(&kefir.build());

        // Reading the table doesn't allocate either
        let slice = DogCodec::encode_alloc(&kefir.build())
            .unwrap()
            .into_fjall_slice();
        let (name_len, allocations) = crate::test_alloc::allocations(|| {
            let flat = DogCodec::decode(&mut DecodingVec::from(&slice)).unwrap();
            let dog = flat.get();
            assert!(dog.belly_shaven());
            dog.name().map(str::len)
        });
        assert_eq!(name_len, Some(5));
        assert_eq!(allocations, 0);
    }
}
